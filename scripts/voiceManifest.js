// Scans public/voice for recorded lines and writes public/voice/manifest.json.
// Runs automatically before `npm run dev` and `npm run build` (predev/prebuild),
// or by hand: npm run voice:manifest
import { readdirSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { VOICE_LINES, VOICE_LINE_INDEX } from '../src/content/VoiceLines.js';

const PREFERENCE = ['ogg', 'mp3', 'wav'];

export function buildManifest(fileNames) {
  const chosen = new Map(); // canonical id -> file
  const unknown = [];
  for (const file of fileNames) {
    const m = /^(.+)\.(ogg|mp3|wav)$/i.exec(file);
    if (!m) continue;
    const line = VOICE_LINE_INDEX.get(m[1]);
    if (!line) {
      unknown.push(file);
      continue;
    }
    const prev = chosen.get(line.id);
    const ext = m[2].toLowerCase();
    if (!prev || PREFERENCE.indexOf(ext) < PREFERENCE.indexOf(prev.split('.').pop().toLowerCase())) chosen.set(line.id, file);
  }
  const files = [...chosen.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([id, file]) => ({ id, file }));
  return { files, unknown };
}

function main() {
  const dir = fileURLToPath(new URL('../public/voice/', import.meta.url));
  mkdirSync(dir, { recursive: true });
  const { files, unknown } = buildManifest(readdirSync(dir));
  const json = `${JSON.stringify({ note: 'Generated by npm run voice:manifest. Do not edit.', files }, null, 2)}\n`;
  let previous = '';
  try {
    previous = readFileSync(`${dir}manifest.json`, 'utf8');
  } catch {
    /* first run */
  }
  if (previous !== json) writeFileSync(`${dir}manifest.json`, json);
  console.log(`voice: ${files.length} of ${VOICE_LINES.length} lines recorded${unknown.length ? `; ignored files with unknown names: ${unknown.join(', ')}` : ''}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
